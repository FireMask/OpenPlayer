"""Write openplayer-carrier.kicad_sch (and .kicad_pro) from netlist.py.

Plain Python; needs KiCad 10 installed for its stock symbol libraries.
Every pin gets a net label at its tip; unused J1 pins get a no-connect flag.
Run: python hardware/pcb/scripts/build_sch.py
"""

import json
import os
import re
import uuid
from pathlib import Path

from netlist import NETS, PARTS, pin_net

PCB_DIR = Path(__file__).resolve().parents[1]
NAME = "openplayer-carrier"
SYMBOL_DIR = Path(os.environ.get("KICAD10_SYMBOL_DIR", r"C:\Program Files\KiCad\10.0\share\kicad\symbols"))
NS = uuid.UUID("5f0c6a52-0c1e-4b8e-9a43-22c0b0a7e0b1")  # fixed: same input → same file

# Sheet position (mm) of each symbol; multiples of 2.54 keep pins on grid.
POSITIONS = {
    "J1": (101.6, 101.6),
    "J2": (172.72, 50.8), "J6": (172.72, 66.04), "J3": (172.72, 81.28),
    "J4": (172.72, 101.6), "J5": (172.72, 132.08),
    "C1": (213.36, 50.8), "C2": (233.68, 50.8),
    "TP1": (213.36, 81.28), "TP2": (226.06, 81.28), "TP3": (238.76, 81.28),
    "H1": (213.36, 109.22), "H2": (226.06, 109.22), "H3": (238.76, 109.22), "H4": (251.46, 109.22),
}
LABEL_ANGLE = {0: 180, 180: 0, 90: 270, 270: 90}  # pin direction → label pointing away from body
JUSTIFY = {0: "left bottom", 180: "right bottom", 90: "left bottom", 270: "right bottom"}


def uid(*parts):
    return str(uuid.uuid5(NS, "/".join(parts)))


def sexpr_block(text, start):
    """Return text[start:end] for the balanced s-expression starting at start."""
    depth, i, in_str = 0, start, False
    while True:
        c = text[i]
        if in_str:
            if c == "\\":
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return text[start:i + 1]
        i += 1


def load_symbol(lib_id):
    """Symbol definition renamed to its lib_id, plus {pin number: (x, y, angle)}."""
    lib, name = lib_id.split(":")
    text = (SYMBOL_DIR / f"{lib}.kicad_sym").read_text(encoding="utf-8")
    block = sexpr_block(text, text.index(f'(symbol "{name}"'))
    assert "(extends" not in block, f"{lib_id} extends another symbol; not supported"
    pins = {}
    for m in re.finditer(r'\(pin \w+ \w+\s*\(at ([-\d.]+) ([-\d.]+) (\d+)\).*?\(number "([^"]+)"', block, re.S):
        pins[m[4]] = (float(m[1]), float(m[2]), int(m[3]))
    return block.replace(f'(symbol "{name}"', f'(symbol "{lib_id}"', 1), pins


def prop(key, value, x, y, hide=False):
    hidden = " (hide yes)" if hide else ""
    return f'(property "{key}" "{value}" (at {x:.2f} {y:.2f} 0){hidden} (effects (font (size 1.27 1.27))))'


def build():
    sheet_uuid = uid("sheet")
    owner = pin_net()
    lib_ids = sorted({sym for _, sym, _ in PARTS.values()})
    symbols = {lib_id: load_symbol(lib_id) for lib_id in lib_ids}

    out = [
        "(kicad_sch",
        "(version 20260101)",
        '(generator "openplayer_build_sch")',
        '(generator_version "10.0")',
        f'(uuid "{sheet_uuid}")',
        '(paper "A4")',
        '(title_block (title "OpenPlayer carrier") (rev "A") (comment 1 "Generated by hardware/pcb/scripts/build_sch.py; do not edit by hand"))',
        "(lib_symbols",
        *(block for block, _ in symbols.values()),
        ")",
    ]
    for ref, (value, lib_id, footprint) in PARTS.items():
        x, y = POSITIONS[ref]
        _, pins = symbols[lib_id]
        if ref == "J1":
            ref_y, value_y = y - 30.48, y + 30.48
        elif ref.startswith("J"):  # stacked 1xN connectors: both texts above the body
            top = y - max(py for _, py, _ in pins.values())
            ref_y, value_y = top - 6.35, top - 3.81
        else:
            ref_y, value_y = y - 5.08, y + 12.7
        out += [
            f'(symbol (lib_id "{lib_id}") (at {x:.2f} {y:.2f} 0) (unit 1)',
            "(exclude_from_sim no) (in_bom yes) (on_board yes) (dnp no)",
            f'(uuid "{uid("sym", ref)}")',
            prop("Reference", ref, x, ref_y),
            prop("Value", value, x, value_y),
            prop("Footprint", footprint, x, y, hide=True),
            prop("Datasheet", "", x, y, hide=True),
            prop("Description", "", x, y, hide=True),
            *(f'(pin "{n}" (uuid "{uid("pin", ref, n)}"))' for n in pins),
            f'(instances (project "{NAME}" (path "/{sheet_uuid}" (reference "{ref}") (unit 1))))',
            ")",
        ]
        for n, (px, py, angle) in pins.items():
            at_x, at_y = round(x + px, 2), round(y - py, 2)  # symbol Y is up, sheet Y is down
            net = owner.get((ref, n))
            if net is None:
                out.append(f'(no_connect (at {at_x:.2f} {at_y:.2f}) (uuid "{uid("nc", ref, n)}"))')
                continue
            out.append(
                f'(label "{net}" (at {at_x:.2f} {at_y:.2f} {LABEL_ANGLE[angle]}) '
                f'(effects (font (size 1.27 1.27)) (justify {JUSTIFY[LABEL_ANGLE[angle]]})) '
                f'(uuid "{uid("label", ref, n)}"))'
            )
    out += ['(sheet_instances (path "/" (page "1")))', "(embedded_fonts no)", ")"]

    (PCB_DIR / f"{NAME}.kicad_sch").write_text("\n".join(out) + "\n", encoding="utf-8")
    pro = PCB_DIR / f"{NAME}.kicad_pro"
    if not pro.exists():  # KiCad and build_pcb.py add settings to it later; never overwrite
        pro.write_text(json.dumps({"meta": {"filename": pro.name, "version": 3}}, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    build()
    print(f"wrote {NAME}.kicad_sch ({sum(map(len, NETS.values()))} connected pins)")
